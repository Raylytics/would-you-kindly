#!/usr/bin/env bash
# Render docs/backlog-snapshot.md: a scrubbed, read-only view of this repo's
# bd tracker so a GitHub visitor can check the README's numbers against the
# issues themselves (would-you-kindly-j9fu).
#
# The pipeline is wyk export -> jq allowlist -> markdown. Only these fields
# survive: id, title, type, status, priority, labels, created date, closed
# date. Owner, assignee, description, notes, dependencies and every other
# field are dropped at the projection, not filtered out afterwards, so a new
# bd field can never leak by default. Labels keep only the contract
# vocabulary (human, src:agent, src:human, meta, review:*): session UUIDs
# are dropped and per-identity src:agent:<name> collapses to src:agent.
# Titles are scrubbed of emails, UUIDs, home-directory paths and every
# pattern in docs/backlog-snapshot.redact.
#
# scripts/backlog-snapshot-check.sh lints the committed file for anything
# that should have been scrubbed; `make check` and CI run it. CI has no bd,
# so regeneration is local: `make backlog-snapshot`, review the diff, commit.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
OUT=${1:-$ROOT/docs/backlog-snapshot.md}
REDACT=$ROOT/docs/backlog-snapshot.redact
REPO=${WYK_SNAPSHOT_REPO:-would-you-kindly}

command -v jq >/dev/null || { echo "backlog-snapshot: jq is required" >&2; exit 1; }

WYK=${WYK:-}
if [ -z "$WYK" ]; then
  TMPBIN=$(mktemp -d)
  trap 'rm -rf "$TMPBIN"' EXIT
  (cd "$ROOT" && go build -o "$TMPBIN/wyk" ./cmd/wyk)
  WYK=$TMPBIN/wyk
fi

# Redaction patterns: one Oniguruma regex per line, # comments and blanks
# ignored. Each match in a title becomes [redacted].
REDACTS=$(grep -v '^\s*#' "$REDACT" 2>/dev/null | grep -v '^\s*$' | jq -R . | jq -s . || echo '[]')
TODAY=$(date -u +%Y-%m-%d)

"$WYK" export -repo "$REPO" -closed -compact | jq -r --arg today "$TODAY" --arg repo "$REPO" --argjson redacts "$REDACTS" '
  def day: if . == null or . == "" then "" else .[0:10] end;
  def epoch: sub("\\.[0-9]+"; "") | sub("Z$"; "+0000")
             | sub("(?<h>[+-][0-9]{2}):(?<m>[0-9]{2})$"; "\(.h)\(.m)")
             | strptime("%Y-%m-%dT%H:%M:%S%z") | mktime;
  def median: sort | if length == 0 then null
                     elif length % 2 == 1 then .[length / 2 | floor]
                     else (.[length / 2 - 1] + .[length / 2]) / 2 end;
  def scrub:
    gsub("[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}"; "[email]")
    | gsub("[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"; "[uuid]")
    | gsub("(/Users|/home)/[^ ]+"; "[path]")
    | reduce $redacts[] as $re (.; gsub($re; "[redacted]"))
    | gsub("\\|"; "\\|");
  def keep_label: . == "human" or . == "src:agent" or . == "src:human" or . == "meta" or startswith("review:");
  def labels: [ (.labels // [])[] | if startswith("src:agent:") then "src:agent" else . end | select(keep_label) ] | unique | join(" ");
  def row: "| \(.id) | \(.status) | P\(.priority) | \(.issue_type) | \(.title | scrub) | \(labels) | \(.created_at | day) |";
  def closed_row: "| \(.id) | P\(.priority) | \(.issue_type) | \(.title | scrub) | \(labels) | \(.created_at | day) | \(.closed_at | day) |";

  (.repos[] | select(.name == $repo) | .issues) as $all
  | ($all | map(select(.status != "closed")) | sort_by(.priority, .id)) as $open
  | ($all | map(select(.status == "closed")) | sort_by(.closed_at, .id) | reverse) as $closed
  | ($all | map(select(.status == "closed" and ((.labels // []) | index("human")) and .closed_at != null and .created_at != null)
           | ((.closed_at | epoch) - (.created_at | epoch)) / 3600) | median) as $human_median_h
  | ($all | map(select((.labels // []) | index("human"))) | length) as $human_total
  | ($all | map(select((.labels // []) | index("src:agent"))) | length) as $agent_filed
  | ($all | group_by(.status) | map({key: .[0].status, value: length}) | from_entries) as $by_status
  | [
      "# Backlog snapshot",
      "",
      "<!-- generated by scripts/backlog-snapshot.sh — do not edit; run `make backlog-snapshot` -->",
      "",
      "Generated: \($today)",
      "",
      "A read-only, scrubbed view of this repo'"'"'s own bd tracker, so the numbers in",
      "the README can be checked against the issues behind them. The live tracker",
      "is not in git (it holds owner emails and working notes); this file keeps",
      "only id, title, type, status, priority, the contract labels",
      "(`human`, `src:agent`, `src:human`, plus `meta` and `review:*`), and",
      "created/closed dates. Titles are scrubbed of emails, UUIDs and paths. See",
      "`docs/CONTRACT.md` for what the labels mean and `docs/WORKFLOW.md` for",
      "the loop they drive.",
      "",
      "## Summary",
      "",
      "| Measure | Value |",
      "|---|---|",
      "| Issues | \($all | length) |",
      ( $by_status | to_entries | sort_by(.key)[] | "| \(.key) | \(.value) |" ),
      "| Human-flagged (lifetime) | \($human_total) |",
      "| Agent-filed (`src:agent`) | \($agent_filed) |",
      "| Median time-to-close, human-flagged | \(if $human_median_h == null then "n/a" else "\(($human_median_h * 10 | round) / 10)h" end) |",
      "",
      "## Not closed (\($open | length))",
      "",
      "| ID | Status | Pri | Type | Title | Labels | Created |",
      "|---|---|---|---|---|---|---|",
      ( $open[] | row ),
      "",
      "## Closed (\($closed | length))",
      "",
      "| ID | Pri | Type | Title | Labels | Created | Closed |",
      "|---|---|---|---|---|---|---|",
      ( $closed[] | closed_row ),
      ""
    ] | join("\n")
' > "$OUT.tmp" && mv "$OUT.tmp" "$OUT"
echo "backlog-snapshot: wrote $OUT"
