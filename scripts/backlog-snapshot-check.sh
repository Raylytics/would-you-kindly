#!/usr/bin/env bash
# Lint docs/backlog-snapshot.md: fail if anything the generator must scrub
# got through (emails, UUIDs, session labels, per-identity agent labels,
# home-directory paths) or if the file's shape drifted from the generator's.
# Runs in `make check` and CI. CI cannot regenerate the file (no bd there),
# so staleness is a warning, not a failure.
set -euo pipefail

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
F=${1:-$ROOT/docs/backlog-snapshot.md}
REDACT=${BACKLOG_SNAPSHOT_REDACT:-$ROOT/docs/backlog-snapshot.redact}
STALE_DAYS=${BACKLOG_SNAPSHOT_STALE_DAYS:-60}

fail() { echo "backlog-snapshot-check: $*" >&2; exit 1; }

command -v jq >/dev/null || fail "jq is required (the redact-list patterns are evaluated with jq, as the generator does)"
[ -f "$F" ] || fail "$F is missing — run 'make backlog-snapshot'"
grep -q '^<!-- generated by scripts/backlog-snapshot.sh' "$F" || fail "missing generator marker"
grep -q '^| ID | Status | Pri | Type | Title | Labels | Created |$' "$F" || fail "not-closed table header drifted"
grep -q '^| ID | Pri | Type | Title | Labels | Created | Closed |$' "$F" || fail "closed table header drifted"

# Anything matching these must never be in the public file.
leaks=0
check() { # <label> <extended regex>
  if hits=$(grep -nE "$2" "$F"); then
    echo "backlog-snapshot-check: $1:" >&2; echo "$hits" | head -5 >&2; leaks=1
  fi
}
check "email address"        '[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}'
check "UUID"                 '[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}'
# A title may talk about the labels ("drops src:/session: labels"); only a
# label VALUE is a leak: session:<uuid> and src:agent:<identity>.
check "session label"        'session:[0-9a-fA-F]{8}-'
check "per-identity label"   'src:agent:[A-Za-z0-9_.-]'
check "home-directory path"  '(/Users|/home)/'
# Any pattern the redact list names must not survive either. The list is
# Oniguruma (jq) syntax, so it is evaluated with jq's test(), the same engine
# the generator's gsub uses — grep -E would silently miss `\d` or `(?i)`
# patterns, or exit 2 and read as "no match" (roborev #6174). A pattern jq
# cannot compile is a hard failure, not a skipped check.
#
# The pattern list comes from the SAME jq filter the generator uses to read
# the file, so the two can never disagree about which lines are patterns:
# indented comments and whitespace-only lines are skipped (a bare `case`
# test let a lone space through and it matched every row), and a final
# pattern with no trailing newline is still read (`while read` alone drops
# it). A missing file is no patterns, as in the generator, but said aloud
# (roborev #6175). The list is captured into a variable, not fed through
# process substitution: bash ignores a process substitution's exit status,
# so a jq failure there (an unreadable file) left the loop empty and the
# check printed ok (roborev #6180). A failure to read the list is fatal —
# these patterns are the leak guard.
if [ -f "$REDACT" ]; then
  patterns=$(jq -r 'split("\n") | map(select(test("^\\s*(#|$)") | not))[]' -Rs "$REDACT") \
    || fail "cannot read redact list $REDACT"
  [ -z "$patterns" ] || while IFS= read -r re; do
    if ! hits=$(jq -R --arg re "$re" 'select(test($re))' "$F" 2>&1); then
      fail "redact-list pattern '$re' is not a valid regex: $hits"
    fi
    if [ -n "$hits" ]; then
      echo "backlog-snapshot-check: redact-list pattern '$re':" >&2; echo "$hits" | head -5 >&2; leaks=1
    fi
  done <<< "$patterns"
else
  echo "backlog-snapshot-check: no redact list at $REDACT; redact-list checks skipped" >&2
fi
[ "$leaks" -eq 0 ] || fail "scrub failures above — fix the generator or docs/backlog-snapshot.redact, then 'make backlog-snapshot'"

# Staleness: a warning only. GitHub Actions renders ::warning:: in the run.
gen=$(sed -n 's/^Generated: \([0-9-]*\)$/\1/p' "$F" | head -1)
[ -n "$gen" ] || fail "missing 'Generated: YYYY-MM-DD' line"
if gen_s=$(date -u -j -f %Y-%m-%d "$gen" +%s 2>/dev/null) || gen_s=$(date -u -d "$gen" +%s 2>/dev/null); then
  age=$(( ( $(date -u +%s) - gen_s ) / 86400 ))
  if [ "$age" -gt "$STALE_DAYS" ]; then
    echo "::warning::docs/backlog-snapshot.md is $age days old — run 'make backlog-snapshot' and commit the result"
  fi
fi
echo "backlog-snapshot-check: ok (generated $gen)"
